#!/usr/bin/env node
// emit-promptfoo.mjs — turn the evals.md cases into a Promptfoo config.
//
// The cases stay the source of truth; this is a build step. Nothing about the
// expectation, the fixture or the verdict moves here: the generated tests carry
// only {skill, case} and a single assertion over the provider's metadata.status.
//
// Usage:
//   node scripts/emit-promptfoo.mjs --tag matrix --models default,opencode-go/gpt-6-luna
//   node scripts/emit-promptfoo.mjs --arms with-skill --tag trigger

import { readdirSync, existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { join, dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { parseCases } from "./lib/evals/parse.mjs"

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const opt = { tag: null, models: ["default"], arms: ["with-skill", "without-skill"], out: join(REPO, "scripts/promptfoo/promptfoo.yaml"), skill: null, case: null }
const argv = process.argv.slice(2)
for (let i = 0; i < argv.length; i++) {
  const a = argv[i]
  if (a === "--tag") opt.tag = argv[++i]
  else if (a === "--models") opt.models = argv[++i].split(",").map((s) => s.trim()).filter(Boolean)
  else if (a === "--arms") opt.arms = argv[++i].split(",").map((s) => s.trim()).filter(Boolean)
  else if (a === "--out") opt.out = resolve(argv[++i])
  else if (a === "--skill") opt.skill = argv[++i]
  else if (a === "--case") opt.case = Number(argv[++i])
}

// Absolute so the generated config works from any --out directory.
const PROVIDER_URL = `file://${join(REPO, "scripts/promptfoo/provider.mjs")}`
const q = (v) => JSON.stringify(v)
const lines = []
function scalar(k, v, indent) {
  const pad = " ".repeat(indent)
  if (v === null || v === undefined) return [`${pad}${k}: null`]
  if (typeof v === "number") return [`${pad}${k}: ${v}`]
  return [`${pad}${k}: ${q(v)}`]
}

const skillsDir = join(REPO, "skills")
const skillIds = readdirSync(skillsDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && existsSync(join(skillsDir, e.name, "references/evals.md")))
  .map((e) => e.name)
  .filter((id) => !opt.skill || id === opt.skill)
  .sort()

const cases = []
for (const id of skillIds) {
  const { cases: parsed } = parseCases(readFileSync(join(skillsDir, id, "references/evals.md"), "utf8"))
  for (const c of parsed) {
    if (c.status !== "run") continue
    if (opt.tag && !c.tags.includes(opt.tag)) continue
    if (opt.case && c.n !== opt.case) continue
    cases.push({ skill: id, c })
  }
}
if (!cases.length) {
  console.error(`no runnable cases${opt.tag ? ` tagged '${opt.tag}'` : ""}`)
  process.exit(1)
}

const out = []
out.push("# Generated by scripts/emit-promptfoo.mjs — do not edit. The cases in")
out.push(`# skills/*/references/evals.md are the source${opt.tag ? `; filtered to tag '${opt.tag}'` : ""}.`)
out.push("")
out.push("prompts:")
out.push(`  - ${q("{{skill}}#{{case}}")}`)
out.push("")
out.push("providers:")
for (const model of opt.models) {
  for (const arm of opt.arms) {
    out.push(`  - id: ${PROVIDER_URL}`)
    out.push(`    label: ${q(`${model} | ${arm}`)}`)
    out.push("    config:")
    out.push(...scalar("model", model === "default" ? null : model, 6))
    out.push(...scalar("arm", arm, 6))
    out.push(...scalar("timeoutMs", 600000, 6))
  }
}
out.push("")
out.push("defaultTest:")
out.push("  assert:")
out.push("    - type: javascript")
out.push(
  `      value: ${q(
    "(() => { const m = context.providerResponse?.metadata; const pass = m?.status === 'passed'; return { pass, score: pass ? 1 : 0, reason: pass ? 'passed' : ((m?.status ?? 'no metadata') + ': ' + (m?.reason ?? '')) }; })()",
  )}`,
)
out.push("")
out.push("tests:")
for (const { skill, c } of cases) {
  out.push(`  - description: ${q(`${skill} #${c.n} — ${c.title}`)}`)
  out.push("    vars:")
  out.push(...scalar("skill", skill, 6))
  out.push(...scalar("case", c.n, 6))
}
out.push("")

mkdirSync(dirname(opt.out), { recursive: true })
writeFileSync(opt.out, out.join("\n"))
console.log(`Wrote ${opt.out}: ${cases.length} case(s) × ${opt.models.length} model(s) × ${opt.arms.length} arm(s)`)
